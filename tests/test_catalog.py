import hashlib
import json
import unittest

from helpers import HarnessTestCase, skill_text


class CatalogTest(HarnessTestCase):
    def setUp(self):
        super().setUp()
        self.core = self.tmp / "catcore"
        self.add("cdv-zeta", skill_text("cdv-zeta", description="Last one, alphabetically.", version="1.2.0", owner="team-b"))
        self.add("cdv-alpha", skill_text("cdv-alpha", description="First one | with a pipe.", version="0.3.0", owner="team-a"))
        (self.core / "skills/cdv-alpha/references").mkdir()
        (self.core / "skills/cdv-alpha/references/more.md").write_text("more\n")

    def add(self, name, text):
        (self.core / "skills" / name).mkdir(parents=True, exist_ok=True)
        (self.core / "skills" / name / "SKILL.md").write_text(text)

    def catalog(self, *args):
        return self.harness("catalog", "--core", str(self.core), *args)

    def read(self, name):
        return (self.core / name).read_text()

    def test_generates_a_table_and_a_registry(self):
        result = self.catalog()
        self.assertEqual(result.returncode, 0, result.stderr)
        text = self.read("CATALOG.md")
        self.assertIn("Generated by `bin/harness catalog`", text)
        self.assertIn("| Skill | Version | Owner | Description |", text)
        self.assertLess(text.index("cdv-alpha"), text.index("cdv-zeta"))
        self.assertIn("| `cdv-alpha` | 0.3.0 | team-a | First one \\| with a pipe. |", text)
        self.assertIn("| `cdv-zeta` | 1.2.0 | team-b | Last one, alphabetically. |", text)
        registry = json.loads(self.read("registry.json"))
        self.assertEqual(registry["schema"], 1)
        self.assertEqual([s["name"] for s in registry["skills"]], ["cdv-alpha", "cdv-zeta"])
        alpha = registry["skills"][0]
        self.assertEqual(
            set(alpha), {"name", "version", "owner", "description", "path", "contentHash"}
        )
        self.assertEqual(alpha["path"], "skills/cdv-alpha")
        self.assertEqual(alpha["version"], "0.3.0")
        self.assertEqual(alpha["owner"], "team-a")
        self.assertEqual(alpha["description"], "First one | with a pipe.")

    def test_content_hash_is_the_sha256_of_the_sha256sum_lines(self):
        self.catalog()
        alpha = json.loads(self.read("registry.json"))["skills"][0]
        lines = ""
        for relative in ["SKILL.md", "references/more.md"]:
            digest = hashlib.sha256((self.core / "skills/cdv-alpha" / relative).read_bytes()).hexdigest()
            lines += f"{digest}  {relative}\n"
        self.assertEqual(alpha["contentHash"], hashlib.sha256(lines.encode()).hexdigest())

    def test_content_hash_changes_with_any_file_in_the_skill(self):
        self.catalog()
        before = json.loads(self.read("registry.json"))["skills"][0]["contentHash"]
        (self.core / "skills/cdv-alpha/references/more.md").write_text("changed\n")
        self.catalog()
        after = json.loads(self.read("registry.json"))["skills"]
        self.assertNotEqual(before, after[0]["contentHash"])

    def test_generation_is_deterministic(self):
        self.catalog()
        first = (self.read("CATALOG.md"), self.read("registry.json"))
        self.catalog()
        second = (self.read("CATALOG.md"), self.read("registry.json"))
        self.assertEqual(first, second)
        self.assertTrue(first[0].endswith("\n") and first[1].endswith("\n"))

    def test_multiline_description_is_folded_to_one_line(self):
        self.add(
            "cdv-alpha",
            "---\nname: cdv-alpha\ndescription: >\n  Line one\n  line two.\nmetadata:\n  version: 0.3.0\n  owner: team-a\n---\n",
        )
        self.catalog()
        self.assertIn("| Line one line two. |", self.read("CATALOG.md"))

    def test_check_exits_1_after_a_description_change_and_0_after_regenerating(self):
        self.assertEqual(self.catalog("--check").returncode, 1)
        self.assertFalse((self.core / "CATALOG.md").exists())
        self.catalog()
        ok = self.catalog("--check")
        self.assertEqual(ok.returncode, 0, ok.stdout + ok.stderr)
        self.add("cdv-zeta", skill_text("cdv-zeta", description="A different description.", version="1.2.0", owner="team-b"))
        before = (self.read("CATALOG.md"), self.read("registry.json"))
        stale = self.catalog("--check")
        self.assertEqual(stale.returncode, 1)
        self.assertIn("CATALOG.md is out of date", stale.stdout)
        self.assertEqual((self.read("CATALOG.md"), self.read("registry.json")), before)
        self.catalog()
        self.assertEqual(self.catalog("--check").returncode, 0)

    def test_check_detects_a_hand_edit_of_either_file(self):
        self.catalog()
        (self.core / "registry.json").write_text(self.read("registry.json").replace("0.3.0", "9.9.9"))
        stale = self.catalog("--check")
        self.assertEqual(stale.returncode, 1)
        self.assertIn("registry.json is out of date", stale.stdout)
        self.assertNotIn("CATALOG.md is out of date", stale.stdout)

    def test_a_skill_that_fails_lint_is_not_cataloged(self):
        self.add("cdv-bad", "---\nname: cdv-bad\n---\n")
        result = self.catalog()
        self.assertEqual(result.returncode, 1)
        self.assertIn("cdv-bad", result.stderr)
        self.assertFalse((self.core / "CATALOG.md").exists())


if __name__ == "__main__":
    unittest.main()
